# --- Cross-entry structural checks ----------------------------------------------------


def _check_dangling_references(
    system_components: Mapping[str, SystemComponent],
    failure_modes: Mapping[str, FailureMode],
    metrics: Mapping[str, Metric],
    metric_recommendations: Mapping[str, MetricRecommendation],
    alert_recommendations: Mapping[str, AlertRecommendation],
    coverage: Mapping[str, CoverageEntry],
    files: Mapping[str, Path],
) -> None:
    """No reference to a nonexistent ID, from any entry (R19; deliberately not scoped to
    user-visible failure modes only, which is R3's narrower text -- R19 broadens it to
    every entry and every reference field)."""
    for component in system_components.values():
        for dep in component.depends_on:
            if dep not in system_components:
                raise _err(
                    files["system_components"],
                    f"system component {component.id!r} depends_on unknown id {dep!r}",
                )
    for fm in failure_modes.values():
        for cause in fm.caused_by:
            if cause not in failure_modes:
                raise _err(
                    files["failure_modes"],
                    f"failure mode {fm.id!r} caused_by unknown id {cause!r}",
                )
    for mr in metric_recommendations.values():
        if mr.metric_id is not None and mr.metric_id not in metrics:
            raise _err(
                files["metric_recommendations"],
                f"metric recommendation {mr.id!r} references unknown metric_id "
                f"{mr.metric_id!r}",
            )
        for fmid in mr.failure_mode_ids:
            if fmid not in failure_modes:
                raise _err(
                    files["metric_recommendations"],
                    f"metric recommendation {mr.id!r} references unknown failure_mode_id "
                    f"{fmid!r}",
                )
    for ar in alert_recommendations.values():
        for fmid in ar.failure_mode_ids:
            if fmid not in failure_modes:
                raise _err(
                    files["alert_recommendations"],
                    f"alert recommendation {ar.id!r} references unknown failure_mode_id "
                    f"{fmid!r}",
                )
    for entry in coverage.values():
        if entry.failure_mode_id not in failure_modes:
            raise _err(
                files["coverage"],
                f"coverage entry references unknown failure_mode_id "
                f"{entry.failure_mode_id!r}",
            )
        for mid in entry.detecting_metric_ids:
            if mid not in metrics:
                raise _err(
                    files["coverage"],
                    f"coverage entry for {entry.failure_mode_id!r} references unknown "
                    f"metric id {mid!r}",
                )
        for mrid in entry.metric_recommendation_ids:
            if mrid not in metric_recommendations:
                raise _err(
                    files["coverage"],
                    f"coverage entry for {entry.failure_mode_id!r} references unknown "
                    f"metric_recommendation id {mrid!r}",
                )
        for arid in entry.alert_ids:
            if arid not in alert_recommendations:
                raise _err(
                    files["coverage"],
                    f"coverage entry for {entry.failure_mode_id!r} references unknown "
                    f"alert id {arid!r}",
                )


def _check_acyclic(failure_modes: Mapping[str, FailureMode], file: Path) -> None:
    """The `caused_by` graph must be acyclic (R3/R19)."""
    unvisited, in_progress, done = 0, 1, 2
    state: dict[str, int] = dict.fromkeys(failure_modes, unvisited)

    def visit(fm_id: str, path: list[str]) -> None:
        state[fm_id] = in_progress
        path.append(fm_id)
        for cause in failure_modes[fm_id].caused_by:
            if state.get(cause) == in_progress:
                cycle = path[path.index(cause) :] + [cause]
                raise _err(file, f"caused_by cycle: {' -> '.join(cycle)}")
            if state.get(cause) == unvisited:
                visit(cause, path)
        path.pop()
        state[fm_id] = done

    for fm_id in failure_modes:
        if state[fm_id] == unvisited:
            visit(fm_id, [])


def _check_coverage_completeness(
    failure_modes: Mapping[str, FailureMode], coverage: Mapping[str, CoverageEntry], file: Path
) -> None:
    """Exactly one coverage entry per failure mode (duplicates are caught at parse time by
    `_load_coverage`; this catches the missing side)."""
    missing = sorted(set(failure_modes) - set(coverage))
    if missing:
        raise _err(file, f"missing coverage entry for failure mode(s): {', '.join(missing)}")


def _check_doc_headers(root: Path) -> None:
    """A file at a derived-doc path that exists but lacks the generated-file header is not
    Blare's to overwrite (R19) -- caught here as well as by `init_inspection`'s narrower,
    no-state-file scenario."""
    header_bytes = GENERATED_DOC_HEADER.encode()
    for entry_filename in _ENTRY_FILENAMES.values():
        doc_path = _doc_path(root, entry_filename)
        if not doc_path.is_file():
            continue
        raw = _read_bytes(doc_path)
        first_line = raw.split(b"\n", 1)[0]
        if first_line != header_bytes:
            raise _err(
                doc_path,
                "lacks the generated-file header; this file is not Blare's to overwrite",
            )


def _load_state(file: Path) -> tuple[str, int]:
    raw = _read_bytes(file)
    try:
        doc = _YAML.load(raw)
    except Exception as exc:  # ruamel's parse failures aren't one exception type
        raise _err(file, f"is not valid YAML ({exc})") from exc
    if not isinstance(doc, dict):
        raise _err(file, "must be a YAML mapping with 'analyzed_sha' and 'schema_version'")
    sha = doc.get("analyzed_sha")
    version = doc.get("schema_version")
    missing = []
    if not isinstance(sha, str) or not sha:
        missing.append("analyzed_sha")
    # bool is an int subclass in Python; excluded explicitly so `true`/`false` don't parse
    # as a schema version.
    if not isinstance(version, int) or isinstance(version, bool):
        missing.append("schema_version")
    if missing:
        raise _err(file, f"is missing required field(s): {', '.join(missing)}")
    assert isinstance(sha, str)
    assert isinstance(version, int)
    return sha, version


def _check_schema_version(file: Path, version: int) -> None:
    if version != CURRENT_SCHEMA_VERSION:
        raise SchemaVersionError(
            cause=(
                f"{file} records schema version {version}, but this Blare understands "
                f"version {CURRENT_SCHEMA_VERSION}"
            ),
            next_action=(
                "Run the Blare version that matches the recorded schema version, or "
                "delete .blare/ and re-run full analysis (this discards any "
                "hand-recorded content)."
            ),
        )


# --- Config and stack resolution (R23) -------------------------------------------------


def _config_error(path: Path, problem: str) -> ConfigError:
    return ConfigError(
        cause=f"{path} {problem}",
        next_action=(
            f"Edit {path} to set 'stack' to one of the supported values: "
            f"{', '.join(supported_stacks())}."
        ),
    )


def _resolve_stack(
    root: Path, *, missing_is_error: bool
) -> tuple[ObservabilityStack, str, bool]:
    """Resolve `config.yaml`'s stack (R23). `missing_is_error` is true only for `load` in
    update mode -- every other caller (`empty_set`, and `load` in analyze mode, R16
    re-analysis included) defaults in memory and lets the write primitives create the file.

    Returns the resolved stack handle, its name, and whether the file existed (write-side
    concern: an existing config is preserved byte-identically and never rewritten).
    """
    path = root / _CONFIG_FILENAME
    if not path.is_file():
        if missing_is_error:
            raise _config_error(path, "does not exist")
        return get_stack(_DEFAULT_STACK_NAME), _DEFAULT_STACK_NAME, False
    # Deliberately not `_read_bytes`: config.yaml is outside R19's scope (spec, Artifacts
    # -- "validated by R23" instead), so an unreadable config must raise `ConfigError`
    # with R23's own next_action, not the generic StructuralValidationError every other
    # canonical file's read failure raises.
    try:
        raw = path.read_bytes()
    except OSError as exc:
        raise _config_error(path, f"could not be read ({exc.strerror or exc})") from exc
    try:
        doc = _YAML.load(raw)
    except Exception as exc:  # ruamel's parse failures aren't one exception type
        raise _config_error(path, f"is not valid YAML ({exc})") from exc
    if not isinstance(doc, dict):
        raise _config_error(path, "does not define a 'stack' value")
    stack_name = doc.get("stack")
    if not isinstance(stack_name, str) or not stack_name.strip():
        raise _config_error(path, "does not define a 'stack' value")
    # An unsupported name propagates get_stack's own UnsupportedStackError unchanged
    # rather than being wrapped here. stack.py's own docstring frames this as artifacts
    # "attaching the file name when propagating it", but there is nothing left to
    # attach: get_stack's next_action already hardcodes the literal ".blare/config.yaml"
    # (the location is fixed, never configurable -- spec, Artifacts), so the message
    # already names the file and, via its cause, the supported values. Left unwrapped on
    # purpose rather than reformatted to use this function's own computed `path` (which
    # could be an absolute Path, unlike the stable relative literal get_stack uses).
    stack = get_stack(stack_name)
    return stack, stack_name, True


# --- Public interface ------------------------------------------------------------------


def state_exists(root: Path) -> bool:
    """Whether `state.yaml` exists -- the R1-vs-R16-vs-R17 mode dispatch."""
    return (root / _STATE_FILENAME).is_file()


def init_inspection(root: Path) -> None:
    """R1's inverse refusal: called only when `state_exists(root)` is false. Refuses,
    naming every offending file, when any canonical entry-based file or derived-doc-path
    file already exists -- an existing `config.yaml` alone never triggers this."""
    offending: list[Path] = []
    for filename in _ENTRY_FILENAMES.values():
        path = root / filename
        if path.exists():
            offending.append(path)
    for filename in _ENTRY_FILENAMES.values():
        doc_path = _doc_path(root, filename)
        if doc_path.exists():
            offending.append(doc_path)
    if offending:
        names = ", ".join(str(p) for p in offending)
        raise PreexistingFilesError(
            cause=f"no state file exists, but these files already do: {names}",
            next_action=(
                "Remove or relocate these files before running blare analyze, or restore "
                "the missing .blare/state.yaml if this codebase was analyzed before."
            ),
        )


def empty_set(root: Path) -> ArtifactSet:
    """The fresh R1 baseline: every entry map empty, no recorded analysis yet. Resolves
    `config.yaml` if present (honoring an unsupported stack's refusal) and defaults to
    Prometheus in memory when absent -- never calls `load`."""
    stack, stack_name, config_existed = _resolve_stack(root, missing_is_error=False)
    return ArtifactSet(
        system_components={},
        failure_modes={},
        metrics={},
        metric_recommendations={},
        alert_recommendations={},
        coverage={},
        analyzed_sha=None,
        schema_version=CURRENT_SCHEMA_VERSION,
        stack_name=stack_name,
        stack=stack,
        config_existed=config_existed,
        raw_bytes={},
        documents={},
    )


def load(root: Path, mode: RunMode) -> ArtifactSet:
    """Load and structurally validate the canonical YAML (R19), resolve config/stack
    (R23), and check the schema version (R24). Raises `StateMissingError` if `state.yaml`
    is absent (the R17 identity) -- the fresh R1 path never reaches here; it starts from
    `empty_set` instead."""
    state_path = root / _STATE_FILENAME
    if not state_exists(root):
        raise StateMissingError(
            cause=f"{state_path} does not exist",
            next_action="Run `blare analyze` first to produce the artifact set.",
        )

    analyzed_sha, schema_version = _load_state(state_path)
    _check_schema_version(state_path, schema_version)

    files: dict[str, Path] = {}
    raw_bytes: dict[str, bytes] = {}
    documents: dict[str, CommentedSeq] = {}
    raw_items: dict[str, CommentedSeq] = {}
    for key, filename in _ENTRY_FILENAMES.items():
        path = root / filename
        files[key] = path
        if not path.is_file():
            raise _err(
                path,
                "does not exist, but state.yaml does (entry files must be present when "
                "state exists)",
            )
        raw, items = _load_entry_list(path)
        raw_bytes[filename] = raw
        documents[filename] = items
        raw_items[key] = items

    system_components = _load_entries(
        files["system_components"], raw_items["system_components"], "sm", _parse_system_component
    )
    failure_modes = _load_entries(
        files["failure_modes"], raw_items["failure_modes"], "fm", _parse_failure_mode
    )
    metrics = _load_entries(files["metrics"], raw_items["metrics"], "mx", _parse_metric)
    metric_recommendations = _load_entries(
        files["metric_recommendations"],
        raw_items["metric_recommendations"],
        "mr",
        _parse_metric_recommendation,
    )
    alert_recommendations = _load_entries(
        files["alert_recommendations"],
        raw_items["alert_recommendations"],
        "ar",
        _parse_alert_recommendation,
    )
    coverage = _load_coverage(files["coverage"], raw_items["coverage"])

    _check_dangling_references(
        system_components,
        failure_modes,
        metrics,
        metric_recommendations,
        alert_recommendations,
        coverage,
        files,
    )
    _check_acyclic(failure_modes, files["failure_modes"])
    _check_coverage_completeness(failure_modes, coverage, files["coverage"])
    _check_doc_headers(root)

    raw_bytes[_STATE_FILENAME] = _read_bytes(state_path)
    stack, stack_name, config_existed = _resolve_stack(
        root, missing_is_error=(mode is RunMode.UPDATE)
    )

    return ArtifactSet(
        system_components=system_components,
        failure_modes=failure_modes,
        metrics=metrics,
        metric_recommendations=metric_recommendations,
        alert_recommendations=alert_recommendations,
        coverage=coverage,
        analyzed_sha=analyzed_sha,
        schema_version=schema_version,
        stack_name=stack_name,
        stack=stack,
        config_existed=config_existed,
        raw_bytes=raw_bytes,
        documents=documents,
    )


def semantic_violations(s: ArtifactSet) -> list[Violation]:
    """R4-R5 in full, plus the excluded-empty-sets property (artifacts.md). Never raises
    for a violating set -- a violating set still loads; this seeds the R18 affected-phase
    queue and drives system-originated amendments. A misbehaving stack (one whose
    `validate_expression` raises rather than returning a verdict) is treated as an
    invalid-expression violation rather than allowed to crash the check."""
    violations: list[Violation] = []

    coverage_fms_by_alert: dict[str, set[str]] = {}
    for cov_entry in s.coverage.values():
        for arid in cov_entry.alert_ids:
            coverage_fms_by_alert.setdefault(arid, set()).add(cov_entry.failure_mode_id)

    for fm in s.failure_modes.values():
        entry = s.coverage.get(fm.id)
        # `load` guarantees a coverage entry for every failure mode; `entry` is only ever
        # None here for a hand-built ArtifactSet in a test that bypasses that guarantee,
        # in which case there is nothing to check for this failure mode.
        if entry is None:
            continue
        if fm.coverage_status == "excluded":
            metric_side_dirty = bool(
                entry.detecting_metric_ids or entry.metric_recommendation_ids
            ) or any(fm.id in mr.failure_mode_ids for mr in s.metric_recommendations.values())
            if metric_side_dirty:
                violations.append(
                    Violation(ViolationKind.EXCLUDED_WITH_METRIC_COVERAGE, (fm.id,))
                )
            alert_side_dirty = bool(entry.alert_ids) or any(
                fm.id in ar.failure_mode_ids for ar in s.alert_recommendations.values()
            )
            if alert_side_dirty:
                violations.append(
                    Violation(ViolationKind.EXCLUDED_WITH_ALERT_COVERAGE, (fm.id,))
                )
        elif not entry.alert_ids:
            violations.append(Violation(ViolationKind.UNMAPPED_FAILURE_MODE, (fm.id,)))

    for mr in s.metric_recommendations.values():
        if not mr.failure_mode_ids:
            violations.append(
                Violation(ViolationKind.EMPTY_LINKAGE_METRIC_RECOMMENDATION, (mr.id,))
            )

    for ar in s.alert_recommendations.values():
        if not ar.failure_mode_ids:
            violations.append(
                Violation(ViolationKind.EMPTY_LINKAGE_ALERT_RECOMMENDATION, (ar.id,))
            )

        try:
            verdict = s.stack.validate_expression(ar.expr)
        except Exception:
            # Defense-in-depth (artifacts.md's failure-mode test plan): a misbehaving
            # stack must not crash the run.
            violations.append(Violation(ViolationKind.INVALID_EXPRESSION, (ar.id,)))
        else:
            if not verdict.ok:
                violations.append(Violation(ViolationKind.INVALID_EXPRESSION, (ar.id,)))

        ranks = [
            _SEVERITY_RANK[s.failure_modes[fmid].severity]
            for fmid in ar.failure_mode_ids
            if fmid in s.failure_modes and s.failure_modes[fmid].severity in _SEVERITY_RANK
        ]
        if ranks:
            max_rank = max(ranks)
            if _SEVERITY_RANK.get(ar.severity, 0) < max_rank:
                violations.append(Violation(ViolationKind.ALERT_SEVERITY_BELOW_MAX, (ar.id,)))

        expected_fms = set(ar.failure_mode_ids)
        actual_fms = coverage_fms_by_alert.get(ar.id, set())
        if expected_fms != actual_fms:
            violations.append(Violation(ViolationKind.LINKAGE_INCONSISTENCY, (ar.id,)))

    return violations


def gap_counts(s: ArtifactSet) -> GapSummary:
    """Non-excluded failure modes split by coverage status (R13)."""
    alertable = metric_gap = excluded = 0
    for fm in s.failure_modes.values():
        if fm.coverage_status == "alertable":
            alertable += 1
        elif fm.coverage_status == "metric-gap":
            metric_gap += 1
        else:
            excluded += 1
    return GapSummary(alertable=alertable, metric_gap=metric_gap, excluded=excluded)


# --- batch_check: the per-batch content check (T1.5) ----------------------------------


def _check_regular_edit_schema(
    s: ArtifactSet,
    batch_phase: Phase,
    edit: Edit,
    live_ids: set[str],
) -> BatchVerdict | None:
    """The content half of the per-batch check for one non-coverage edit: phase
    consistency, payload schema (reusing the same parser `load` uses), and -- for alert
    edits -- expression syntax and rule-field validation via the set's stack. `live_ids`
    is the set of ids that exist *as of this point in the batch* -- it starts as a copy
    of every id already in `s` and is updated in place as ADD/REMOVE edits are processed
    (added on ADD, discarded on REMOVE), so a batch that adds an id and then updates or
    removes that same id later in the same batch is validated against the batch's actual
    running effect rather than a static pre-batch snapshot. Returns `None` when the edit
    passes, or the rejecting verdict."""
    spec = _TYPE_SPECS[edit.entry_type]
    assert spec.phase is not None and spec.prefix is not None  # not "coverage"
    if spec.phase is not batch_phase:
        return BatchVerdict(
            ok=False,
            message=(
                f"edit tagged for phase {batch_phase.value} targets "
                f"{edit.entry_type!r}, which belongs to phase {spec.phase.value}"
            ),
        )
    file = Path(spec.filename)

    if edit.op is EditOp.REMOVE:
        id_ = edit.payload_or_id
        if not isinstance(id_, str) or not id_:
            return BatchVerdict(ok=False, message="remove op requires a non-empty string id")
        # `live_ids` is a flattened union across every non-coverage entry type (ids are
        # globally unique, artifacts.md), so membership alone doesn't catch a remove
        # tagged with the wrong entry_type but naming a real id from a *different* type
        # -- e.g. removing a metric id through a "system_components" edit. Reject that
        # explicitly rather than letting it through to silently no-op in apply() (a
        # dict.pop on the wrong map never raises, so it would report success without
        # doing anything).
        if not id_.startswith(f"{spec.prefix}-"):
            return BatchVerdict(
                ok=False,
                message=(
                    f"remove targets {id_!r}, which does not use the {spec.prefix!r}- "
                    f"prefix required for {edit.entry_type!r}"
                ),
            )
        if id_ not in live_ids:
            return BatchVerdict(ok=False, message=f"remove targets unknown id {id_!r}")
        live_ids.discard(id_)
        return None

    payload = edit.payload_or_id
    if not isinstance(payload, dict):
        return BatchVerdict(
            ok=False,
            message=f"{edit.op.value} op on {edit.entry_type!r} requires a mapping payload",
        )
    try:
        id_ = _extract_prefixed_id(file, payload, spec.prefix)
    except StructuralValidationError as exc:
        return BatchVerdict(ok=False, message=exc.cause)

    if edit.op is EditOp.ADD and id_ in live_ids:
        return BatchVerdict(ok=False, message=f"duplicate id {id_!r}")
    if edit.op is EditOp.UPDATE and id_ not in live_ids:
        return BatchVerdict(ok=False, message=f"update targets unknown id {id_!r}")

    try:
        entry = spec.parser(file, id_, payload)
    except StructuralValidationError as exc:
        return BatchVerdict(ok=False, message=exc.cause)

    if edit.entry_type == "alert_recommendations":
        assert isinstance(entry, AlertRecommendation)
        rule_input = AlertRuleInput(
            name=entry.name,
            expr=entry.expr,
            for_duration=entry.for_duration,
            severity=entry.severity,
            annotations=dict(entry.annotations),
        )
        try:
            expr_verdict = s.stack.validate_expression(entry.expr)
        except Exception as exc:  # defense-in-depth: a misbehaving stack must not crash
            return BatchVerdict(ok=False, message=f"stack raised validating expression: {exc}")
        if not expr_verdict.ok:
            return BatchVerdict(ok=False, message=expr_verdict.message or "invalid expression")
        try:
            fields_verdict = s.stack.validate_rule_fields(rule_input)
        except Exception as exc:  # same defense, for the rule-fields validator
            return BatchVerdict(ok=False, message=f"stack raised validating rule fields: {exc}")
        if not fields_verdict.ok:
            return BatchVerdict(ok=False, message=fields_verdict.message or "invalid rule fields")

    if edit.op is EditOp.ADD:
        live_ids.add(id_)
    return None


_METRIC_SIDE_KEYS = frozenset({"detecting_metric_ids", "metric_recommendation_ids"})
_ALERT_SIDE_KEYS = frozenset({"alert_ids"})


def _check_coverage_edit_schema(
    s: ArtifactSet, batch_phase: Phase, edit: Edit
) -> BatchVerdict | None:
    """The content half of the per-batch check for one coverage edit: only `update` is
    ever legal (coverage keys are mechanical, artifacts.md), the batch must be tagged
    phase 3 or 4, and the payload may only carry that phase's owned side."""
    if edit.op is not EditOp.UPDATE:
        return BatchVerdict(
            ok=False,
            message=(
                "coverage entries accept only update ops -- their keys are mechanical "
                f"(op was {edit.op.value})"
            ),
        )
    if batch_phase not in (Phase.METRIC_COVERAGE, Phase.ALERT_RECOMMENDATIONS):
        return BatchVerdict(
            ok=False,
            message=(
                f"coverage edits must be tagged phase 3 or phase 4, got phase {batch_phase.value}"
            ),
        )
    payload = edit.payload_or_id
    if not isinstance(payload, dict):
        return BatchVerdict(ok=False, message="coverage update requires a mapping payload")
    fm_id = payload.get("failure_mode_id")
    if not isinstance(fm_id, str) or not fm_id:
        return BatchVerdict(
            ok=False, message="coverage update requires a non-empty string 'failure_mode_id'"
        )
    if fm_id not in s.failure_modes:
        return BatchVerdict(
            ok=False, message=f"coverage update targets unknown failure_mode_id {fm_id!r}"
        )

    owned_keys = _METRIC_SIDE_KEYS if batch_phase is Phase.METRIC_COVERAGE else _ALERT_SIDE_KEYS
    other_keys = _ALERT_SIDE_KEYS if batch_phase is Phase.METRIC_COVERAGE else _METRIC_SIDE_KEYS
    present_other = other_keys & payload.keys()
    if present_other:
        return BatchVerdict(
            ok=False,
            message=(
                f"phase {batch_phase.value} coverage edit for {fm_id!r} touches the "
                f"other side's field(s): {', '.join(sorted(present_other))}"
            ),
        )
    for key in owned_keys & payload.keys():
        value = payload[key]
        if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
            return BatchVerdict(ok=False, message=f"{key!r} must be a list of strings")
    return None


def batch_check(s: ArtifactSet, b: EditBatch) -> BatchVerdict:
    """The per-batch content check (architecture, Edit-proposal protocol): payload
    schema, phase consistency (the tagged phase's owned side for coverage entries), and
    R19's structural rules -- uniqueness, reference integrity including removals,
    acyclicity -- applied to the resulting candidate, so an accepted batch always passes
    its own next load. Never raises for a content problem (`BatchVerdict.ok=False`
    carries the reason instead); only a programmer error (an unrecognized `entry_type`
    reaching `apply` after passing every check above, which cannot happen through this
    function's own dispatch) would propagate."""
    # The ids that exist as of "now" while walking the batch in order -- starts as every
    # id already in `s` and is updated in place by `_check_regular_edit_schema` as
    # ADD/REMOVE edits are processed, so an ADD followed later in the same batch by an
    # UPDATE or REMOVE of that same id validates against the batch's running effect
    # rather than a static pre-batch snapshot (a batch is never required to touch each
    # id only once).
    live_ids = (
        set(s.system_components)
        | set(s.failure_modes)
        | set(s.metrics)
        | set(s.metric_recommendations)
        | set(s.alert_recommendations)
    )

    for edit in b.edits:
        if edit.entry_type not in _TYPE_SPECS:
            return BatchVerdict(ok=False, message=f"unknown entry_type {edit.entry_type!r}")
        if edit.entry_type == "coverage":
            verdict = _check_coverage_edit_schema(s, b.phase, edit)
        else:
            verdict = _check_regular_edit_schema(s, b.phase, edit, live_ids)
        if verdict is not None:
            return verdict

    candidate = apply(s, b)

    files = {key: Path(spec.filename) for key, spec in _TYPE_SPECS.items()}
    try:
        _check_dangling_references(
            candidate.system_components,
            candidate.failure_modes,
            candidate.metrics,
            candidate.metric_recommendations,
            candidate.alert_recommendations,
            candidate.coverage,
            files,
        )
        _check_acyclic(candidate.failure_modes, files["failure_modes"])
        _check_coverage_completeness(candidate.failure_modes, candidate.coverage, files["coverage"])
    except StructuralValidationError as exc:
        return BatchVerdict(ok=False, message=exc.cause)

    return BatchVerdict(ok=True)


# --- apply: the pure candidate, with mechanical coverage completeness (T1.5) ----------


def _apply_add_update_or_remove[EntryT](
    edit: Edit,
    target: dict[str, EntryT],
    file: Path,
    prefix: str,
    parser: Callable[[Path, str, Mapping[str, object]], EntryT],
) -> str:
    """Mutate `target` (a copy `apply` owns, never the caller's) in place per `edit`'s
    op; returns the affected id -- `apply`'s failure-mode bookkeeping uses it to drive
    mechanical coverage completeness, every other entry type ignores it. Assumes `edit`
    already passed `batch_check`'s content validation; a malformed edit reaching here
    (bypassing `batch_check`) is a programmer error and raises."""
    if edit.op is EditOp.REMOVE:
        id_ = edit.payload_or_id
        assert isinstance(id_, str), "remove op must carry a string id"
        target.pop(id_, None)
        return id_
    payload = edit.payload_or_id
    assert isinstance(payload, dict), f"{edit.op.value} op must carry a mapping payload"
    id_ = _extract_prefixed_id(file, payload, prefix)
    target[id_] = parser(file, id_, payload)
    return id_


def _coerce_str_tuple(value: object) -> tuple[str, ...]:
    if isinstance(value, tuple):
        return cast(tuple[str, ...], value)
    assert isinstance(value, list), "coverage side field must be a list of strings"
    return tuple(value)


def _apply_coverage_edit(edit: Edit, phase: Phase, coverage: dict[str, CoverageEntry]) -> None:
    """Merge one coverage edit's owned side into `coverage` in place, leaving the other
    side untouched (architecture: "apply merges the owned side and leaves the other
    untouched")."""
    payload = edit.payload_or_id
    assert isinstance(payload, dict), "coverage update must carry a mapping payload"
    fm_id = payload["failure_mode_id"]
    assert isinstance(fm_id, str)
    existing = coverage.get(fm_id, CoverageEntry(fm_id, (), (), ()))
    if phase is Phase.METRIC_COVERAGE:
        coverage[fm_id] = CoverageEntry(
            failure_mode_id=fm_id,
            detecting_metric_ids=_coerce_str_tuple(
                payload.get("detecting_metric_ids", existing.detecting_metric_ids)
            ),
            metric_recommendation_ids=_coerce_str_tuple(
                payload.get("metric_recommendation_ids", existing.metric_recommendation_ids)
            ),
            alert_ids=existing.alert_ids,
        )
    else:
        coverage[fm_id] = CoverageEntry(
            failure_mode_id=fm_id,
            detecting_metric_ids=existing.detecting_metric_ids,
            metric_recommendation_ids=existing.metric_recommendation_ids,
            alert_ids=_coerce_str_tuple(payload.get("alert_ids", existing.alert_ids)),
        )


def apply(s: ArtifactSet, b: EditBatch) -> ArtifactSet:
    """Apply `b` to `s`, returning a new `ArtifactSet` -- pure, `s` is never mutated
    (architecture: "a later apply must return a new ArtifactSet rather than mutate this
    one in place"). Coverage completeness is mechanical, never the agent's: adding a
    failure mode creates its empty coverage entry in the candidate, removing one deletes
    it -- so no reachable candidate can violate the one-entry-per-failure-mode rule
    (artifacts.md)."""
    system_components = dict(s.system_components)
    failure_modes = dict(s.failure_modes)
    metrics = dict(s.metrics)
    metric_recommendations = dict(s.metric_recommendations)
    alert_recommendations = dict(s.alert_recommendations)
    coverage = dict(s.coverage)

    added_failure_modes: set[str] = set()
    removed_failure_modes: set[str] = set()

    for edit in b.edits:
        if edit.entry_type == "system_components":
            _apply_add_update_or_remove(
                edit, system_components, Path("system-map.yaml"), "sm", _parse_system_component
            )
        elif edit.entry_type == "failure_modes":
            fm_id = _apply_add_update_or_remove(
                edit, failure_modes, Path("failure-modes.yaml"), "fm", _parse_failure_mode
            )
            if edit.op is EditOp.ADD:
                added_failure_modes.add(fm_id)
                removed_failure_modes.discard(fm_id)
            elif edit.op is EditOp.REMOVE:
                removed_failure_modes.add(fm_id)
                added_failure_modes.discard(fm_id)
        elif edit.entry_type == "metrics":
            _apply_add_update_or_remove(edit, metrics, Path("metrics.yaml"), "mx", _parse_metric)
        elif edit.entry_type == "metric_recommendations":
            _apply_add_update_or_remove(
                edit,
                metric_recommendations,
                Path("metric-recommendations.yaml"),
                "mr",
                _parse_metric_recommendation,
            )
        elif edit.entry_type == "alert_recommendations":
            _apply_add_update_or_remove(
                edit,
                alert_recommendations,
                Path("alert-recommendations.yaml"),
                "ar",
                _parse_alert_recommendation,
            )
        elif edit.entry_type == "coverage":
            continue  # handled in the second pass below, after mechanical completeness
        else:
            raise ValueError(f"unknown entry_type {edit.entry_type!r}")

    for fm_id in added_failure_modes:
        coverage.setdefault(fm_id, CoverageEntry(fm_id, (), (), ()))
    for fm_id in removed_failure_modes:
        coverage.pop(fm_id, None)

    for edit in b.edits:
        if edit.entry_type == "coverage":
            _apply_coverage_edit(edit, b.phase, coverage)

    return ArtifactSet(
        system_components=system_components,
        failure_modes=failure_modes,
        metrics=metrics,
        metric_recommendations=metric_recommendations,
        alert_recommendations=alert_recommendations,
        coverage=coverage,
        analyzed_sha=s.analyzed_sha,
        schema_version=s.schema_version,
        stack_name=s.stack_name,
        stack=s.stack,
        config_existed=s.config_existed,
        raw_bytes=s.raw_bytes,
        documents=s.documents,
    )


# --- referencing_phases: the reference half of the amendment blast radius (T1.5) ------


def referencing_phases(s: ArtifactSet, changed_ids: set[str]) -> set[Phase]:
    """The phases owning entries that reference any id in `changed_ids` -- coverage
    entries attributed by side (metric side references -> phase 3, alert side -> phase
    4, artifacts.md). One hop only: the orchestrator's amendment recompute is what loops
    this to a fixpoint over a growing changed-id set, not this function."""
    phases: set[Phase] = set()
    for component in s.system_components.values():
        if any(dep in changed_ids for dep in component.depends_on):
            phases.add(Phase.SYSTEM_MAP)
    for fm in s.failure_modes.values():
        if any(cause in changed_ids for cause in fm.caused_by):
            phases.add(Phase.FAILURE_MODES)
    for mr in s.metric_recommendations.values():
        if (mr.metric_id is not None and mr.metric_id in changed_ids) or any(
            fmid in changed_ids for fmid in mr.failure_mode_ids
        ):
            phases.add(Phase.METRIC_COVERAGE)
    for ar in s.alert_recommendations.values():
        if any(fmid in changed_ids for fmid in ar.failure_mode_ids):
            phases.add(Phase.ALERT_RECOMMENDATIONS)
    for cov in s.coverage.values():
        if any(mid in changed_ids for mid in cov.detecting_metric_ids) or any(
            mrid in changed_ids for mrid in cov.metric_recommendation_ids
        ):
            phases.add(Phase.METRIC_COVERAGE)
        if any(arid in changed_ids for arid in cov.alert_ids):
            phases.add(Phase.ALERT_RECOMMENDATIONS)
    return phases


