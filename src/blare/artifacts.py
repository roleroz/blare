class StructuralValidationError(BlareError):
    """One of R19's structural rules failed on load: schema conformance, a dangling
    reference, a `caused_by` cycle, a missing required field, a missing exclusion reason,
    a missing or duplicate coverage entry, an unparseable or incomplete state file, an
    unreadable or missing entry file, or a headerless file at a derived-doc path. Cause
    names the file and the exact problem, verbatim (R13)."""


class StateMissingError(BlareError):
    """`load` (or `state_exists`'s caller) found no `state.yaml` (R17's identity): `blare
    update` needs a prior `blare analyze`. Message names `blare analyze` as the fix."""


class PreexistingFilesError(BlareError):
    """`init_inspection` found canonical entry-based files or derived-doc-path files with
    no state file present (R1's inverse refusal). An existing `config.yaml` alone never
    triggers this. Cause names every offending file."""


class ConfigError(BlareError):
    """`config.yaml` is missing (update mode only, R23), unparseable, or parses without a
    usable `stack` value (empty/null document included). Names the file and the supported
    stack values. An *unsupported* stack name is not this error: it propagates stack's own
    `UnsupportedStackError` unchanged, which already names the file's fixed path (it is
    never configurable, spec's Artifacts section) and the supported values."""


class SchemaVersionError(BlareError):
    """`state.yaml`'s `schema_version` does not match `CURRENT_SCHEMA_VERSION` (R24).
    Cause names both versions; distinct from `StructuralValidationError` since the
    recovery (run the matching Blare version, or discard and re-analyze) differs from a
    plain data-shape fix."""


class WriteError(BlareError):
    """A write primitive (T1.5) failed partway through -- the underlying filesystem
    operation raised (R20's crash case). Cause names the failing file; next_action
    points at git as the recovery, since Blare never commits and `write_state` -- the
    last primitive in the orchestrator's write order -- has not yet run, so the old
    analyzed SHA still matches whatever landed on disk (architecture, Write path)."""


