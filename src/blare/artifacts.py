# --- Small parsing helpers -----------------------------------------------------------


def _err(file: Path, problem: str) -> StructuralValidationError:
    return StructuralValidationError(
        cause=f"{file}: {problem}",
        next_action=(
            "Fix the file by hand (see the problem above), or restore .blare/ from git, "
            "then re-run blare."
        ),
    )


def _doc_path(root: Path, entry_filename: str) -> Path:
    return root / _DOCS_DIRNAME / f"{Path(entry_filename).stem}.md"


def _read_bytes(path: Path) -> bytes:
    try:
        return path.read_bytes()
    except OSError as exc:
        raise _err(path, f"could not be read ({exc.strerror or exc})") from exc


def _str_field(file: Path, item: Mapping[str, object], key: str, desc: str) -> str:
    value = item.get(key)
    if not isinstance(value, str) or not value:
        raise _err(file, f"{desc} is missing a non-empty string {key!r}")
    return value


def _optional_str_field(
    file: Path, item: Mapping[str, object], key: str, desc: str
) -> str | None:
    if key not in item or item[key] is None:
        return None
    value = item[key]
    if not isinstance(value, str):
        raise _err(file, f"{desc}'s {key!r} must be a string")
    return value


def _bool_field(file: Path, item: Mapping[str, object], key: str, desc: str) -> bool:
    value = item.get(key)
    if not isinstance(value, bool):
        raise _err(file, f"{desc} is missing a boolean {key!r}")
    return value


def _enum_field(
    file: Path, item: Mapping[str, object], key: str, desc: str, allowed: Sequence[str]
) -> str:
    value = item.get(key)
    if value not in allowed:
        raise _err(file, f"{desc}'s {key!r} must be one of {list(allowed)}, got {value!r}")
    assert isinstance(value, str)  # narrowed by the membership check above
    return value


def _str_list_field(
    file: Path, item: Mapping[str, object], key: str, desc: str
) -> tuple[str, ...]:
    value = item.get(key, [])
    if value is None:
        value = []
    if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
        raise _err(file, f"{desc}'s {key!r} must be a list of strings")
    return tuple(value)


def _str_map_field(
    file: Path,
    item: Mapping[str, object],
    key: str,
    desc: str,
    required_keys: Sequence[str],
) -> dict[str, str]:
    value = item.get(key)
    if not isinstance(value, dict) or not all(
        isinstance(k, str) and isinstance(v, str) for k, v in value.items()
    ):
        raise _err(file, f"{desc}'s {key!r} must be a mapping of strings")
    missing = [k for k in required_keys if k not in value]
    if missing:
        raise _err(file, f"{desc}'s {key!r} is missing required key(s): {', '.join(missing)}")
    return dict(value)


# --- Per-file loading: entry list -> raw bytes + parsed YAML root --------------------


def _load_entry_list(path: Path) -> tuple[bytes, CommentedSeq]:
    raw = _read_bytes(path)
    try:
        doc = _YAML.load(raw)
    except Exception as exc:  # ruamel's parse failures aren't one exception type
        raise _err(path, f"is not valid YAML ({exc})") from exc
    if doc is None:
        doc = CommentedSeq()
    if not isinstance(doc, list):
        raise _err(path, "must be a YAML list of entries")
    for index, item in enumerate(doc):
        if not isinstance(item, dict):
            raise _err(path, f"entry at index {index} is not a mapping")
    # ruamel's round-trip loader always produces a CommentedSeq for a YAML list; the
    # isinstance(doc, list) check above only narrows mypy to the builtin `list` protocol.
    return raw, cast(CommentedSeq, doc)


def _extract_prefixed_id(
    file: Path, item: Mapping[str, object], prefix: str, index: int | None = None
) -> str:
    """Extract and validate an entry's `id`: non-empty string, carrying `prefix`'s
    required `<prefix>-` form. Shared by `_load_entries` (load-time, `index` given for
    the error message) and T1.5's batch-check/apply (no `index`, since a batch edit's
    payload isn't drawn from an indexed list) -- the one place this rule is enforced,
    so the two call sites can never drift (artifacts.md: "a prefix in the wrong file is
    a schema-conformance failure")."""
    id_ = item.get("id")
    if not isinstance(id_, str) or not id_:
        loc = f"entry at index {index}" if index is not None else "entry"
        raise _err(file, f"{loc} is missing a non-empty string 'id'")
    if not id_.startswith(f"{prefix}-"):
        raise _err(
            file,
            f"id {id_!r} does not use the {prefix!r}- prefix required in {file.name}",
        )
    return id_


def _load_entries[EntryT](
    file: Path,
    raw_items: Sequence[Mapping[str, object]],
    prefix: str,
    parser: Callable[[Path, str, Mapping[str, object]], EntryT],
) -> dict[str, EntryT]:
    """Build `{id: parsed entry}`, enforcing id presence, this file's required prefix, and
    within-file uniqueness. A prefix mismatch is a schema-conformance failure -- since
    every file only ever accepts its own prefix, this is what makes per-file uniqueness
    equal to the set's global uniqueness (artifacts.md)."""
    result: dict[str, EntryT] = {}
    for index, item in enumerate(raw_items):
        id_ = _extract_prefixed_id(file, item, prefix, index)
        if id_ in result:
            raise _err(file, f"duplicate id {id_!r}")
        result[id_] = parser(file, id_, item)
    return result


def _extract_coverage_key(file: Path, item: Mapping[str, object], index: int | None = None) -> str:
    """Extract and validate a coverage entry's `failure_mode_id` -- the one entry type
    keyed by something other than a prefixed `id` (artifacts.md). Shared by
    `_load_coverage` and T1.5's batch-check/apply, same reasoning as
    `_extract_prefixed_id`."""
    fm_id = item.get("failure_mode_id")
    if not isinstance(fm_id, str) or not fm_id:
        loc = f"entry at index {index}" if index is not None else "entry"
        raise _err(file, f"{loc} is missing a non-empty string 'failure_mode_id'")
    return fm_id


def _parse_coverage_entry(file: Path, fm_id: str, item: Mapping[str, object]) -> CoverageEntry:
    desc = f"coverage entry for {fm_id!r}"
    return CoverageEntry(
        failure_mode_id=fm_id,
        detecting_metric_ids=_str_list_field(file, item, "detecting_metric_ids", desc),
        metric_recommendation_ids=_str_list_field(file, item, "metric_recommendation_ids", desc),
        alert_ids=_str_list_field(file, item, "alert_ids", desc),
    )


def _load_coverage(
    file: Path, raw_items: Sequence[Mapping[str, object]]
) -> dict[str, CoverageEntry]:
    result: dict[str, CoverageEntry] = {}
    for index, item in enumerate(raw_items):
        fm_id = _extract_coverage_key(file, item, index)
        if fm_id in result:
            raise _err(file, f"duplicate coverage key (failure_mode_id) {fm_id!r}")
        result[fm_id] = _parse_coverage_entry(file, fm_id, item)
    return result


# --- Per-type field parsers -----------------------------------------------------------


def _parse_system_component(
    file: Path, id_: str, item: Mapping[str, object]
) -> SystemComponent:
    desc = f"system component {id_!r}"
    return SystemComponent(
        id=id_,
        name=_str_field(file, item, "name", desc),
        kind=_enum_field(file, item, "kind", desc, _COMPONENT_KINDS),
        description=_str_field(file, item, "description", desc),
        depends_on=_str_list_field(file, item, "depends_on", desc),
    )


def _parse_failure_mode(file: Path, id_: str, item: Mapping[str, object]) -> FailureMode:
    desc = f"failure mode {id_!r}"
    coverage_status = _enum_field(file, item, "coverage_status", desc, _COVERAGE_STATUSES)
    exclusion_reason = _optional_str_field(file, item, "exclusion_reason", desc)
    if coverage_status == "excluded" and not exclusion_reason:
        raise _err(file, f"{desc} is excluded but has no 'exclusion_reason'")
    return FailureMode(
        id=id_,
        title=_str_field(file, item, "title", desc),
        description=_str_field(file, item, "description", desc),
        severity=_enum_field(file, item, "severity", desc, _SEVERITIES),
        user_visible=_bool_field(file, item, "user_visible", desc),
        caused_by=_str_list_field(file, item, "caused_by", desc),
        coverage_status=coverage_status,
        exclusion_reason=exclusion_reason,
    )


def _parse_metric(file: Path, id_: str, item: Mapping[str, object]) -> Metric:
    desc = f"metric {id_!r}"
    return Metric(
        id=id_,
        name=_str_field(file, item, "name", desc),
        type=_enum_field(file, item, "type", desc, _METRIC_TYPES),
        labels=_str_list_field(file, item, "labels", desc),
        emitted_at=_str_list_field(file, item, "emitted_at", desc),
        description=_str_field(file, item, "description", desc),
    )


def _parse_metric_recommendation(
    file: Path, id_: str, item: Mapping[str, object]
) -> MetricRecommendation:
    desc = f"metric recommendation {id_!r}"
    kind = _enum_field(file, item, "kind", desc, _RECOMMENDATION_KINDS)
    metric_id = _optional_str_field(file, item, "metric_id", desc)
    if kind == "change" and metric_id is None:
        raise _err(file, f"{desc} has kind 'change' but no 'metric_id'")
    if kind == "new" and metric_id is not None:
        raise _err(file, f"{desc} has kind 'new' but specifies 'metric_id'")
    if metric_id is not None and not metric_id.startswith("mx-"):
        raise _err(file, f"{desc}'s metric_id {metric_id!r} does not use the 'mx-' prefix")
    return MetricRecommendation(
        id=id_,
        kind=kind,
        metric_id=metric_id,
        failure_mode_ids=_str_list_field(file, item, "failure_mode_ids", desc),
        rationale=_str_field(file, item, "rationale", desc),
        details=_str_field(file, item, "details", desc),
    )


def _parse_alert_recommendation(
    file: Path, id_: str, item: Mapping[str, object]
) -> AlertRecommendation:
    desc = f"alert recommendation {id_!r}"
    return AlertRecommendation(
        id=id_,
        name=_str_field(file, item, "name", desc),
        expr=_str_field(file, item, "expr", desc),
        for_duration=_str_field(file, item, "for_duration", desc),
        severity=_enum_field(file, item, "severity", desc, _SEVERITIES),
        failure_mode_ids=_str_list_field(file, item, "failure_mode_ids", desc),
        annotations=_str_map_field(file, item, "annotations", desc, ("summary", "description")),
    )


